CREATE OR REPLACE TABLE CUSTOMER_ML_DATA AS
WITH CUSTOMER_ORDER_STATS AS
(
    SELECT
        C.C_CUSTKEY AS CUSTOMER_ID,
        C.C_ACCTBAL,
        C.C_MKTSEGMENT,
        COUNT(O.O_ORDERKEY) AS TOTAL_ORDERS,
        COALESCE(SUM(O.O_TOTALPRICE), 0) AS TOTAL_SPENDING,
        COALESCE(AVG(O.O_TOTALPRICE), 0) AS AVG_ORDER_VALUE
    FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER C
    LEFT JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS O
        ON C.C_CUSTKEY = O.O_CUSTKEY
    GROUP BY
        C.C_CUSTKEY,
        C.C_ACCTBAL,
        C.C_MKTSEGMENT
),
AVERAGE_SPENDING AS
(
    SELECT
        AVG(TOTAL_SPENDING) AS AVG_SPENDING
    FROM CUSTOMER_ORDER_STATS
)
SELECT
    C.CUSTOMER_ID,
    C.C_ACCTBAL,
    C.C_MKTSEGMENT,
    C.TOTAL_ORDERS,
    C.TOTAL_SPENDING,
    C.AVG_ORDER_VALUE,
    CASE
        WHEN C.TOTAL_SPENDING > A.AVG_SPENDING
        THEN 1
        ELSE 0
    END AS HIGH_VALUE
FROM CUSTOMER_ORDER_STATS C
CROSS JOIN AVERAGE_SPENDING A;


SELECT *
FROM CUSTOMER_ML_DATA
LIMIT 10;


SELECT
    COUNT(*) AS TOTAL_CUSTOMERS,
    COUNT_IF(TOTAL_ORDERS > 0) AS CUSTOMERS_WITH_ORDERS,
    COUNT_IF(TOTAL_SPENDING > 0) AS CUSTOMERS_WITH_SPENDING
FROM CUSTOMER_ML_DATA;


SELECT
    HIGH_VALUE,
    COUNT(*) AS CUSTOMER_COUNT
FROM CUSTOMER_ML_DATA
GROUP BY HIGH_VALUE
ORDER BY HIGH_VALUE;
