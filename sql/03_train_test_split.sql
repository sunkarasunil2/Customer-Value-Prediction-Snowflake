CREATE OR REPLACE TABLE CUSTOMER_TRAIN AS
SELECT
    CUSTOMER_ID,
    C_ACCTBAL,
    C_MKTSEGMENT,
    TOTAL_ORDERS,
    AVG_ORDER_VALUE,
    HIGH_VALUE
FROM CUSTOMER_ML_DATA
WHERE UNIFORM(0::FLOAT, 1::FLOAT, RANDOM()) < 0.8;


CREATE OR REPLACE TABLE CUSTOMER_TEST AS
SELECT
    CUSTOMER_ID,
    C_ACCTBAL,
    C_MKTSEGMENT,
    TOTAL_ORDERS,
    AVG_ORDER_VALUE,
    HIGH_VALUE
FROM CUSTOMER_ML_DATA
WHERE CUSTOMER_ID NOT IN
(
    SELECT CUSTOMER_ID
    FROM CUSTOMER_TRAIN
);


SELECT
    'TRAIN' AS DATASET,
    COUNT(*) AS ROW_COUNT
FROM CUSTOMER_TRAIN

UNION ALL

SELECT
    'TEST' AS DATASET,
    COUNT(*) AS ROW_COUNT
FROM CUSTOMER_TEST;


SELECT
    'TRAIN' AS DATASET,
    HIGH_VALUE,
    COUNT(*) AS CUSTOMER_COUNT
FROM CUSTOMER_TRAIN
GROUP BY HIGH_VALUE

UNION ALL

SELECT
    'TEST' AS DATASET,
    HIGH_VALUE,
    COUNT(*) AS CUSTOMER_COUNT
FROM CUSTOMER_TEST
GROUP BY HIGH_VALUE

ORDER BY DATASET, HIGH_VALUE;
